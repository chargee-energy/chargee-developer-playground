// Derive a flat endpoint registry from openapi.json so the UI can map any
// concrete request back to its operationId/tag and build a Swagger UI
// deep-link ("View in API docs"). Run as part of `npm run api:generate`.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const SPEC = resolve(__dirname, '..', 'openapi.json')
const OUT = resolve(__dirname, '..', 'src', 'api', 'endpoints.generated.ts')

const spec = JSON.parse(readFileSync(SPEC, 'utf8'))
const METHODS = ['get', 'post', 'put', 'patch', 'delete']

const endpoints = []
for (const [path, item] of Object.entries(spec.paths ?? {})) {
  for (const method of METHODS) {
    const op = item[method]
    if (!op) continue
    endpoints.push({
      method: method.toUpperCase(),
      path,
      operationId: op.operationId ?? '',
      tag: (op.tags && op.tags[0]) ?? 'default',
      summary: op.summary ?? op.description ?? '',
    })
  }
}

endpoints.sort((a, b) => a.tag.localeCompare(b.tag) || a.path.localeCompare(b.path))

const banner = `// AUTO-GENERATED by scripts/gen-endpoints.mjs — do not edit by hand.\n// Regenerate with \`npm run api:generate\`.\n`
const body = `export interface ApiEndpoint {
  method: string
  path: string
  operationId: string
  tag: string
  summary: string
}

export const API_ENDPOINTS: ApiEndpoint[] = ${JSON.stringify(endpoints, null, 2)}
`

writeFileSync(OUT, banner + '\n' + body)
console.log(`✓ Wrote ${OUT} (${endpoints.length} endpoints)`)
